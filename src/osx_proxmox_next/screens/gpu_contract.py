"""What the GPU screen mixins share with each other and with the host screen.

The mixins (ChooseMixin, BiosMixin, RunMixin, RestartMixin, AttachMixin, BootMixin, CardBusyMixin) are mixed into
GpuScreen and call each other's methods and read its state through ``self``. This base declares that surface once
so a type checker can follow it. It exists for the checker only: at run time ``GpuHost`` is plain ``object``, so
the class hierarchy and the method resolution order of GpuScreen are exactly what they were without it.

The signatures below mirror the real definitions (gpu.py, gpu_run.py, gpu_choose.py, gpu_attach_step.py); change
them together."""
from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Callable
    from typing import Any

    from rich.text import Text
    from textual.widget import Widget

    from ..gpu_setup import Session
    from .base import OsxScreen
    from .gpu_run import Guidance

    class GpuHost(OsxScreen):
        s: Session
        mode: str
        vmid: int | None
        fixed_vm: bool
        working: bool
        progress: str
        result_text: str
        result_fail: bool
        waiting_for_restart: bool
        failed: dict[str, str]
        picked_plan: Any
        _phase_started: dict[str, float]
        _token: int

        @property
        def durations(self) -> dict[str, float]: ...
        def job(self, work: Callable[[], Any], done: Callable[[Any], None], note: str = "") -> None: ...
        def say(self, text: str, fail: bool = False) -> None: ...
        def drive(self) -> None: ...
        def action_back(self) -> None: ...
        def read_refit(self) -> None: ...
        def _vm_name(self, vmid: int) -> str: ...
        def _job_card_changed(self, exc: Exception) -> None: ...
        async def set_mode(self, mode: str, widgets: list[Widget]) -> None: ...
        def start_phase(self, pid: str) -> None: ...
        def end_phase(self, pid: str, seconds: float | None = None) -> None: ...
        def set_actions(self, primary: Callable[[], None] | None, secondary: Callable[[], None] | None = None) -> None: ...
        def paint_run(self) -> None: ...
        def timeline(self, first_boot: bool = False) -> Text: ...
        def _guidance(self, g: Guidance) -> None: ...
        async def show_run(self, title: str, lines: list[str], buttons: list[tuple[str, str, str]],
                           tone: str = "", muted: tuple[int, ...] = ()) -> None: ...
        async def _show_choose(self, notice: str = "") -> None: ...
        def _fill_releases(self) -> None: ...
        def _pick_changed(self) -> None: ...
        def step_verify(self) -> None: ...
else:
    GpuHost = object
