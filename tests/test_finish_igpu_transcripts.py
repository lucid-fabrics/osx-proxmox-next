TS = re.compile(r"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(\.\d+)?Z?")


def current(name):
    for m in MODS:
        if hasattr(m, name):
            return getattr(m, name)
    return None


TMP = ""
REPO = str(Path(igpu_engine.__file__).resolve().parents[2])


def short(text):
    """An argument list as a log line: without the temporary directory (which differs per run), cut at 160 characters."""
    return TS.sub("<ts>", text.replace(TMP, "<tmp>").replace(REPO, "<repo>"))[:160]


def spy(mp, log, name, mods=MODS):
    for m in mods:
        if hasattr(m, name):
            orig = getattr(m, name)

            def wrapper(*a, _orig=orig, _name=name, **k):
                log.append(("call", _name, short(repr(a)), sorted(k)))
                return _orig(*a, **k)

            mp.setattr(m, name, wrapper)


def set_all(mp, name, value):
    hit = False
    for m in MODS:
        if hasattr(m, name):
            mp.setattr(m, name, value)
            hit = True
    assert hit, name


def instrument(mp, log, pve, console, clock):
    orig = pve.qm

    def qm(*a):
        r = orig(*a)
        log.append(("qm", clock.now) + a + (r.ok, r.output.strip()[:60]))
        return r

    pve.qm = qm
    for meth in ("type_text", "sendkey", "restore_picker_timeout", "save_frame"):
        if hasattr(console, meth):
            o = getattr(console, meth)

            def w(*a, _o=o, _m=meth):
                r = _o(*a)
                log.append(("console", _m) + a + (r,))
                return r

            setattr(console, meth, w)
    for name in (
        "create_snapshot",
        "resolve_recovery_or_installer_path",
        "prepare_attach_igpu",
        "check_intel_gpu",
        "ensure_igpu_assets",
        "apply_plan",
        "open_recovery_terminal",
        "fetch_vm_info",
        "stage_recovery",
        "wait_stopped",
        "_drop_disk",
        "_import_disk",
    ):
        spy(mp, log, name)
    for name in ("build_payload", "read_result", "check_accel", "write_state", "picks_state", "describe_state", "strip_args"):
        spy(mp, log, name, [igpu_engine])
    from osx_proxmox_next import driver_engine, driver_disks

    for name in ("write_record", "from_igpu_state"):
        spy(mp, log, name, [driver_engine])
    for name in ("fingerprint", "release_maps", "volume_paths"):
        spy(mp, log, name, [driver_disks])
    orig_unlink = Path.unlink

    def unlink(self, *a, **k):
        log.append(("unlink", self.name))
        return orig_unlink(self, *a, **k)

    mp.setattr(Path, "unlink", unlink)


def norm(text):
    return TS.sub("<ts>", text)


def tree(root):
    out = {}
    for p in sorted(root.rglob("*")):
        if p.is_file():
            try:
                out[str(p.relative_to(root))] = norm(p.read_text())
            except UnicodeDecodeError:
                out[str(p.relative_to(root))] = "<bin %d>" % p.stat().st_size
    return out


def record(name, env, mp, pve, console=None, **kw):
    global TMP
    TMP = str(env.tmp)
    log, events = [], []
    clock = Clock()
    console = console or Console()
    if hasattr(console, "clock"):
        console.clock = clock
    instrument(mp, log, pve, console, clock)

    def on_event(m):
        log.append(("event", m))
        events.append(m)

    try:
        res = igpu_finish.finish(
            9,
            console=console,
            pve=pve,
            iso_dir=env.tmp,
            on_event=on_event,
            clock=clock.monotonic,
            sleep=clock.sleep,
            work_dir=env.tmp,
            **kw,
        )
        outcome = {"result": dataclasses.asdict(res)}
    except BaseException as e:  # noqa
        outcome = {"exc": "%s: %s" % (type(e).__name__, e)}
    RESULTS[name] = {
        "log": [list(map(str, x)) for x in log],
        "outcome": outcome,
        "applied": env.applied,
        "asked": [sorted(k) for k in env.asked],
        "end": clock.now,
        "pve_cfg": pve.cfg,
        "pve_status": pve.status,
        "console": [console.typed, console.keys],
        "files": sorted(p.name for p in env.tmp.iterdir()),
        "state": tree(env.tmp / "state") if (env.tmp / "state").exists() else {},
    }


def reads(mp, seq, rest="installed"):
    items = iter(seq)
    mp.setattr(igpu_engine, "read_result", lambda path: next(items, rest))


