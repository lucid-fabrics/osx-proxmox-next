class Gone(Pve):
    def qm(self, *a):
        return CommandResult(False, 2, "no such VM") if a[0] == "status" else super().qm(*a)


class OneStart(Pve):
    def qm(self, *a):
        if a[0] == "start" and len([c for c in self.calls if c[0] == "start"]) >= 1:
            self.calls.append(a)
            return CommandResult(False, 1, "boom")
        return super().qm(*a)


class SetFails(Pve):
    def qm(self, *a):
        if a[0] == "set" and len(a) > 2 and a[2] == "--sata2":
            self.calls.append(a)
            return CommandResult(False, 1, "bad slot")
        return super().qm(*a)


class Interrupted(Pve):
    def qm(self, *a):
        if a[0] == "start" and sum(1 for c in self.calls if c[:2] == ("start", "9")) >= 1:
            self.calls.append(a)
            self.status = "running"
            raise KeyboardInterrupt
        return super().qm(*a)


