def settled(name, env):
    """What the case recorded, with the temporary directory and memory addresses taken out."""
    text = TS.sub("<ts>", json.dumps(RESULTS[name], sort_keys=True, default=str))
    for path in {str(env.tmp), str(env.tmp.resolve())}:
        text = text.replace(path, "<tmp>")
    text = text.replace(REPO, "<repo>")
    return json.loads(re.sub(r"0x[0-9a-f]{6,}", "0x?", text))


@pytest.fixture(scope="module")
def golden():
    if os.environ.get("GOLDEN_WRITE"):
        return {}
    with gzip.open(GOLDEN, "rt") as fh:
        return json.load(fh)


@pytest.fixture(scope="module", autouse=True)
def _write_golden():
    yield
    if os.environ.get("GOLDEN_WRITE"):
        with gzip.open(os.environ["GOLDEN_WRITE"], "wt", compresslevel=9) as fh:
            json.dump(SETTLED, fh, sort_keys=True, separators=(",", ":"))


def test_the_golden_file_holds_exactly_these_cases(golden):
    assert os.environ.get("GOLDEN_WRITE") or sorted(golden) == sorted(SCENARIOS)


@pytest.mark.parametrize("name", sorted(SCENARIOS))
def test_golden(name, env, accel, monkeypatch, golden):
    env.accel = accel
    kw = SCENARIOS[name](env, monkeypatch)
    if kw.pop("slow", False):
        pass
    seen = kw.pop("seen", None)
    record(name, env, monkeypatch, **kw)
    if seen is not None:
        RESULTS[name]["seen"] = seen
    RESULTS[name]["accel_calls"] = accel.calls
    SETTLED[name] = settled(name, env)
    assert golden == {} or SETTLED[name] == golden[name]
