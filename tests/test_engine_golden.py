def _fake_subprocess_run(argv, **kw):
    import subprocess
    CALLS.append(("subprocess", list(argv)))
    key = " ".join(argv)
    ans = {"efibootmgr -v": (0, EFI_GRUB), "pveversion": (0, "pve-manager/9.2.24/x\n"), "dmesg": (0, "DMAR-IR: Enabled IRQ remapping\n"),
           "mokutil --sb-state": (0, "SecureBoot disabled")}
    if key in ans:
        rc, out = ans[key]
    elif argv and argv[0] in ("update-grub", "update-initramfs", "proxmox-boot-tool", "modprobe", "depmod", "dkms", "lspci", "qm", "pct"):
        rc, out = 0, ""
    else:
        raise FileNotFoundError(argv[0] if argv else "")
    return subprocess.CompletedProcess(argv, rc, out, "")


def snap(root):
    out = {}
    for base, dirs, files in os.walk(root):
        for name in dirs + files:
            full = os.path.join(base, name)
            rel = os.path.relpath(full, root)
            if os.path.islink(full):
                out[rel] = "-> " + os.readlink(full)
            elif name in files:
                try:
                    with open(full) as fh:
                        out[rel] = fh.read()
                except UnicodeDecodeError:
                    out[rel] = "<binary %d>" % os.path.getsize(full)
            else:
                out[rel] = "<dir>"
    return out


def run_case(mod, argv, stdin, setup, patches=(), fakes=None):
    shutil.rmtree(SB, ignore_errors=True)
    SB.mkdir(parents=True)
    env = {"DRIVER_STATE_DIR": str(SB / "driver"), "IGPU_STATE_DIR": str(SB / "igpu"), "GPU_ROOT": str(SB / "root"),
           "GPU_SYSFS": str(SB / "root" / "sys"), "SYSFS_ROOT": str(SB / "root" / "sys"), "IGPU_DEVICES_OFFLINE": "1",
           "IGPU_DEVICES_CACHE": str(SB / "cache"), "IGPU_DEVICES": ""}
    with contextlib.ExitStack() as st:
        st.enter_context(mock.patch.dict(os.environ, env))
        os.environ.pop("IGPU_DEVICES", None)
        st.enter_context(mock.patch("subprocess.run", _fake_subprocess_run))
        st.enter_context(mock.patch("time.time", lambda: NOW))
        st.enter_context(mock.patch("time.localtime", lambda *a: _REAL_GMTIME(NOW)))
        st.enter_context(mock.patch("time.strftime", lambda fmt, t=None: _REAL_STRFTIME(fmt, _REAL_GMTIME(NOW) if t is None else t)))
        st.enter_context(mock.patch("time.gmtime", lambda secs=None: _REAL_GMTIME(NOW if secs is None else secs)))
        st.enter_context(mock.patch("urllib.request.urlopen", side_effect=OSError("no network in the harness")))
        for (m, name), fake in (fakes or {}).items():
            st.enter_context(mock.patch.object(m, name, fake))
        st.enter_context(mock.patch.object(de, "now_iso", lambda: "2026-11-23T00:00:00Z"))
        CALLS.clear()
        setup()
        before = snap(SB)
        CALLS.clear()
        out, err = io.StringIO(), io.StringIO()
        exc = None
        rv = "unset"
        with mock.patch.object(sys, "stdin", io.StringIO(stdin)), contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            try:
                rv = mod.main(["prog"] + argv)
            except BaseException as e:  # noqa
                exc = "%s: %s" % (type(e).__name__, e)
        after = snap(SB)
        changed = {k: v for k, v in after.items() if before.get(k) != v}
        gone = sorted(k for k in before if k not in after)
        res = {"rv": repr(rv), "out": out.getvalue(), "err": err.getvalue(), "exc": exc, "calls": [list(map(str, c)) for c in CALLS],
               "fs": {k: v if v in ("<dir>",) or v.startswith(("->", "<binary")) else hashlib.sha1(v.encode()).hexdigest()[:10]
                      for k, v in changed.items()}, "gone": gone}
        return json.loads(json.dumps(res).replace(str(SB), "<sb>"))


def tails(good, extra=("x", "y")):
    seen, res = set(), []
    for k in range(len(good) + 1):
        res.append(list(good[:k]))
    for n in range(1, len(extra) + 1):
        res.append(list(good) + list(extra[:n]))
    out = []
    for t in res:
        if tuple(t) not in seen:
            seen.add(tuple(t))
            out.append(t)
    return out


