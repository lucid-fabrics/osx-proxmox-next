@pytest.mark.parametrize("engine", sorted(RUNNERS))
def test_every_command_prints_and_returns_what_it_did_before_the_split(engine, golden, written, tmp_path_factory):
    global SB
    SB = tmp_path_factory.mktemp(engine) / "sb"
    results = {}
    RUNNERS[engine](results)
    results = {k.replace(str(SB), "<sb>"): v for k, v in results.items()}
    shutil.rmtree(SB, ignore_errors=True)
