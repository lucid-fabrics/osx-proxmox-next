"""The order of the checks verify_host returns, the commands it and plan_host run on the host, and the plan plan_binding builds, on fake
host trees. The expected values in tests/data/host_flows.json were generated by running this file against main
(GOLDEN_WRITE=<path> writes them instead of comparing), so a reordered check, an extra `dmesg` or a moved snapshot shows up here."""
from __future__ import annotations

import gzip
import json
import os
from pathlib import Path
from types import SimpleNamespace

import pytest

from gpu_fakes import EFI_GRUB, EFI_SDBOOT, FakeRun, add_card, add_other, make_host, write
from nullmoth_fakes import add_dev
from osx_proxmox_next import host_setup as hs

GOLDEN = Path(__file__).parent / "data" / "host_flows.json.gz"
CMDLINE = {"intel": "BOOT_IMAGE=/x ro intel_iommu=on iommu=pt", "amd": "BOOT_IMAGE=/x ro iommu=pt"}
TABLES = {"intel": ("DMAR",), "amd": ("IVRS",)}
BOOTLOADERS = {"grub": EFI_GRUB, "systemd-boot": EFI_SDBOOT}
MODULES = "vfio 1 0 - Live 0x0\nvfio_iommu_type1 1 0 - Live 0x0\nvfio_pci 1 0 - Live 0x0\n"
IDS_LINE = "options vfio-pci ids=1002:73ff,1002:ab28 disable_vga=1\n"
RESULTS: dict = {}


@pytest.fixture(autouse=True)
def _kernel(monkeypatch):
    monkeypatch.setattr(os, "uname", lambda: SimpleNamespace(release="6.8.12-1-pve"))


def host(tmp_path, cpu, driver="vfio-pci", extra=""):
    root = make_host(tmp_path, cpu=cpu, cmdline=CMDLINE[cpu], tables=TABLES[cpu])
    add_card(root, driver=driver)
    write(root, "/proc/modules", MODULES)
    if extra == "stray":
        add_other(root, "0000:07:00.0", 0x144D, 0xA808, 0x010802, 7)
        add_other(root, "0000:00:1c.0", 0x8086, 0x1111, 0x060400, 7)
    elif extra == "twin":
        add_card(root, bdf="0000:09:00", group=8)
    elif extra == "twin-covered":
        add_card(root, bdf="0000:09:00", group=8)
        write(root, "/etc/modprobe.d/vfio.conf", IDS_LINE)
    elif extra in ("partial", "partial-twin"):
        add_dev(root / "sys", "0000:06:00.2", 0x1022, 0x15B6, cls=0x0C0330, driver="xhci_hcd", group=7)
        add_dev(root / "sys", "0000:06:00.3", 0x1002, 0xA808, cls=0x010802, driver="nvme", group=7)
        if extra == "partial-twin":
            add_card(root, bdf="0000:09:00", group=8)
    elif extra == "ids-line":
        write(root, "/etc/modprobe.d/vfio.conf", "options vfio-pci ids=10de:2504\n")
    return str(root)


def settle(root, bdf, vendor):
    """Write what the plan for this card changes on the host, as an earlier apply would have, then hand the card to vfio-pci."""
    run = new_run("grub")
    target = hs.build_target(root, bdf, vendor, "none")
    for change in hs.plan_host(hs.detect_facts(root, run, env={}), target, None, root, run)["changes"]:
        write(Path(root), change["path"], change["new"])
    for fn in sorted((Path(root) / "sys/bus/pci/devices").glob(bdf + ".*")):
        link = fn / "driver"
        if link.is_symlink():
            link.unlink()
        drivers = Path(root) / "sys/bus/pci/drivers/vfio-pci"
        drivers.mkdir(parents=True, exist_ok=True)
        link.symlink_to(drivers)


def dumped(value):
    return json.loads(json.dumps(value, sort_keys=True, default=str))


def record(name, value):
    RESULTS[name] = dumped(value)
    if not os.environ.get("GOLDEN_WRITE"):
        with gzip.open(GOLDEN, "rt") as fh:
            assert RESULTS[name] == json.load(fh)[name]


@pytest.fixture(scope="module", autouse=True)
def _write_golden():
    yield
    if os.environ.get("GOLDEN_WRITE"):
        with gzip.open(os.environ["GOLDEN_WRITE"], "wt", compresslevel=9) as fh:
            json.dump(RESULTS, fh, sort_keys=True, indent=0)


def new_run(bootloader):
    return FakeRun({"efibootmgr -v": (0, BOOTLOADERS[bootloader]), "dmesg": (0, "DMAR-IR: Enabled IRQ remapping in x2apic mode"),
                    "pveversion": (0, "pve-manager/9.2.24/x\n")})


@pytest.mark.parametrize("extra", ["clean", "stray"])
@pytest.mark.parametrize("bootloader", sorted(BOOTLOADERS))
@pytest.mark.parametrize("cpu", ["intel", "amd"])
def test_verify_host_returns_the_checks_in_order_and_runs_the_same_commands(tmp_path, cpu, bootloader, extra):
    root = host(tmp_path, cpu, extra=extra)
    run = new_run(bootloader)
    checks = hs.verify_host(hs.build_target(root, "0000:06:00", "amd", "early-bind"), root, run)
    record("verify/%s/%s/%s" % (cpu, bootloader, extra),
           {"ids": [c["id"] for c in checks], "status": [c["status"] for c in checks], "checks": checks, "run": run.calls})


@pytest.mark.parametrize("name,kw", [
    ("no-modules", {"modules": ""}), ("amdgpu-driver", {"driver": "amdgpu"}), ("no-cmdline", {"cmdline": "BOOT_IMAGE=/x ro"}),
    ("dmesg-quiet", {"dmesg": "nothing"}), ("moved-card", {"identity": {"vendor": 0x1002, "device": 0x1111, "bdf": "0000:06:00"}}),
])
def test_verify_host_failures_keep_their_order_and_their_commands(tmp_path, name, kw):
    root = host(tmp_path, "intel", driver=kw.get("driver", "vfio-pci"))
    if "modules" in kw:
        write(Path(root), "/proc/modules", kw["modules"])
    if "cmdline" in kw:
        write(Path(root), "/proc/cmdline", kw["cmdline"] + "\n")
    run = new_run("grub")
    if "dmesg" in kw:
        run.answers["dmesg"] = (0, kw["dmesg"])
    target = hs.build_target(root, "0000:06:00", "amd", "early-bind")
    if "identity" in kw:
        target["identity"] = kw["identity"]
    checks = hs.verify_host(target, root, run)
    record("verify-fail/" + name, {"ids": [c["id"] for c in checks], "status": [c["status"] for c in checks], "run": run.calls})


BINDING_CASES = [("unbound", "amdgpu", "clean"), ("bound-nothing-at-boot", "vfio-pci", "clean"), ("bound-at-boot", "vfio-pci", "bound-at-boot"),
                 ("unbound-stray", "amdgpu", "stray"), ("twin", "amdgpu", "twin"), ("twin-bound", "vfio-pci", "twin"),
                 ("twin-covered", "amdgpu", "twin-covered"), ("ids-line", "amdgpu", "ids-line"),
                 ("partial", "amdgpu", "partial"), ("partial-twin", "amdgpu", "partial-twin")]


@pytest.mark.parametrize("name,driver,extra", BINDING_CASES)
@pytest.mark.parametrize("bootloader", sorted(BOOTLOADERS))
@pytest.mark.parametrize("cpu", ["intel", "amd"])
def test_plan_host_and_plan_binding_build_the_same_plan_with_the_same_commands(tmp_path, cpu, bootloader, name, driver, extra):
    root = host(tmp_path, cpu, driver=driver, extra=extra)
    if extra == "bound-at-boot":
        settle(root, "0000:06:00", "amd")
    run = new_run(bootloader)
    facts = hs.detect_facts(root, run, env={})
    target = hs.build_target(root, "0000:06:00", "amd", "early-bind")
    plan = hs.plan_host(facts, target, None, root, run)
    after_plan_host = list(run.calls)
    binding = hs.new_plan()
    hs.plan_binding(facts, target, root, binding, {"write_optional": True})
    record("plan/%s/%s/%s" % (cpu, bootloader, name), {"plan": plan, "run": after_plan_host, "binding": binding, "run_after": run.calls})


@pytest.mark.parametrize("bootloader", sorted(BOOTLOADERS))
@pytest.mark.parametrize("reset", ["early-bind", "vendor-reset", "vendor-reset-warn"])
def test_plan_host_for_the_iGPU_and_for_the_vendor_reset_runs_its_commands_in_order(tmp_path, bootloader, reset):
    root = make_host(tmp_path, cpu="intel", cmdline=CMDLINE["intel"], tables=TABLES["intel"])
    add_dev(root / "sys", "0000:00:02.0", 0x8086, 0x46A6, cls=0x030000, driver="i915", group=3)
    run = new_run(bootloader)
    run.answers["dkms status"] = (0, "")
    facts = hs.detect_facts(str(root), run, env={})
    intel = hs.plan_host(facts, hs.build_target(str(root), "0000:00:02", "intel", "none"), None, str(root), run)
    after_intel = list(run.calls)
    settle(str(root), "0000:00:02", "intel")
    run.calls.clear()
    held = hs.plan_host(hs.detect_facts(str(root), run, env={}), hs.build_target(str(root), "0000:00:02", "intel", "none"), None, str(root), run)
    after_held = list(run.calls)
    add_card(root)
    facts = hs.detect_facts(str(root), run, env={})
    amd = hs.plan_host(facts, hs.build_target(str(root), "0000:06:00", "amd", reset), None, str(root), run)
    record("plan-extra/%s/%s" % (bootloader, reset), {"intel": intel, "after_intel": after_intel, "held": held, "after_held": after_held, "amd": amd, "run": run.calls})
