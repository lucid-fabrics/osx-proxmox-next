def short(text):
    """An argument list as a log line: without the temporary directory (which differs per run), cut at 160 characters."""
    return re.sub(r"0x[0-9a-f]{6,}", "0x?", TS.sub("<ts>", text.replace(TMP, "<tmp>").replace(REPO + "/", "<repo>/")))[:160]


def spy(mp, log, name, mods=MODS):
    for m in mods:
        if hasattr(m, name):
            orig = getattr(m, name)

            def wrapper(*a, _orig=orig, _name=name, **k):
                log.append(("call", _name, short(repr(a)), sorted(k)))
                return _orig(*a, **k)

            mp.setattr(m, name, wrapper)


def set_all(mp, name, value):
    hit = False
    for m in MODS:
        if hasattr(m, name):
            mp.setattr(m, name, value)
            hit = True
    assert hit, name


def instrument(mp, log, pve, console, clock):
    orig = pve.qm

    def qm(*a):
        r = orig(*a)
        log.append(("qm", clock.now) + a + (r.ok, r.output.strip()[:60]))
        return r

    pve.qm = qm
    for meth in ("type_text", "sendkey", "restore_picker_timeout", "save_frame"):
        if hasattr(console, meth):
            o = getattr(console, meth)

            def w(*a, _o=o, _m=meth):
                r = _o(*a)
                log.append(("console", _m) + a + (r,))
                return r

            setattr(console, meth, w)
    for name in (
        "create_snapshot",
        "resolve_recovery_or_installer_path",
        "ensure_amfipass",
        "apply_plan",
        "open_recovery_terminal",
        "fetch_vm_info",
        "stage_recovery",
        "wait_stopped",
        "_drop_disk",
        "_import_disk",
    ):
        spy(mp, log, name)
    for name in ("prepare_attach",):
        spy(mp, log, name, [nullmoth])
    for name in ("resolve", "fetch_release", "firmware_pins", "fetch_firmware", "build_payload", "payload_files", "read_result"):
        spy(mp, log, name, [engine])
    for name in ("read_result",):
        spy(mp, log, name, [igpu_engine])
    for name in ("write_record",):
        spy(mp, log, name, [driver_engine])
    for name in ("fingerprint", "release_maps", "volume_paths"):
        spy(mp, log, name, [driver_disks])
    spy(mp, log, "write_marker", [driver_oc])
    orig_unlink = Path.unlink

    def unlink(self, *a, **k):
        log.append(("unlink", self.name))
        return orig_unlink(self, *a, **k)

    mp.setattr(Path, "unlink", unlink)


def tree(root):
    out = {}
    for p in sorted(root.rglob("*")):
        if p.is_file():
            try:
                out[str(p.relative_to(root))] = TS.sub("<ts>", p.read_text())
            except UnicodeDecodeError:
                out[str(p.relative_to(root))] = "<bin %d>" % p.stat().st_size
    return out


def record(name, env, mp, pve, console=None, find=lambda mac: "", probe=lambda ip, port: True, **kw):
    global TMP
    TMP = str(env.tmp)
    log, events = [], []
    clock = Clock()
    console = console or Console()
    env.pve = pve
    instrument(mp, log, pve, console, clock)

    def on_event(m):
        log.append(("event", m))
        events.append(m)

    def find_w(mac):
        r = find(mac)
        log.append(("find_ip", mac, r))
        return r

    def probe_w(ip, port):
        r = probe(ip, port)
        log.append(("probe", ip, port, r))
        return r

    choice = kw.pop("choice", "latest")
    try:
        res = nf.finish(
            9,
            "0000:01:00.0",
            choice,
            console=console,
            pve=pve,
            iso_dir=env.tmp,
            on_event=on_event,
            clock=clock.monotonic,
            sleep=clock.sleep,
            work_dir=kw.pop("work_dir", env.tmp),
            find_ip=find_w,
            probe=probe_w,
            **kw,
        )
        outcome = {"result": dataclasses.asdict(res)}
    except BaseException as e:  # noqa: BLE001 - records the KeyboardInterrupt a scenario raises
        outcome = {"exc": "%s: %s" % (type(e).__name__, e)}
    RESULTS[name] = {
        "log": [list(map(str, x)) for x in log],
        "outcome": outcome,
        "applied": env.applied,
        "built": env.built,
        "end": clock.now,
        "pve_cfg": pve.cfg,
        "pve_status": pve.status,
        "console": [console.typed, console.keys],
        "files": sorted(str(p.relative_to(env.tmp)) for p in env.tmp.rglob("*")),
        "state": tree(env.tmp / "state") if (env.tmp / "state").exists() else {},
    }


class Gone(Pve):
    def qm(self, *a):
        return CommandResult(False, 2, "no such VM") if a[0] == "status" else super().qm(*a)


class Refusing(Pve):
    def qm(self, *a):
        if a[0] == "set" and a[2] == "--sata1":
            self.calls.append(a)
            return CommandResult(False, 1, "bad slot")
        return super().qm(*a)


class SecondStartFails(Pve):
    def __init__(self, *a, **k):
        super().__init__(*a, **k)
        self.starts = 0

    def qm(self, *a):
        if a[0] == "start":
            self.starts += 1
            if self.starts == 2:
                self.calls.append(a)
                return CommandResult(False, 1, "no memory")
        return super().qm(*a)


class Interrupted(Pve):
    def qm(self, *a):
        if a[0] == "start" and sum(1 for c in self.calls if c[:2] == ("start", "9")) >= 1:
            self.calls.append(a)
            self.status = "running"
            raise KeyboardInterrupt
        return super().qm(*a)


